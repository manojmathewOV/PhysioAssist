/**
 * Full real-human benchmark (all 63 recordings). Needs the prepared dataset:
 *   python3 scripts/fixtures/telerehab_prepare.py <dir> --subjects 1,2,3,4,5,6,7,8
 *   RECORDED_DIR=<dir> BENCHMARK_OUT=docs/benchmarks/REAL_HUMAN_RESULTS.md \
 *     npx jest src/testing/recordedPatient/__tests__/benchmark.test.ts
 */
import fs from 'fs';
import path from 'path';
import { analyseRecording, RecordingResult } from '../analyseRecording';
import { loadFixture } from '../loadFixture';

const dir = process.env.RECORDED_DIR;

(dir ? it : it.skip)('writes the real-human benchmark', () => {
  const results: RecordingResult[] = fs
    .readdirSync(dir!)
    .filter((f) => f.endsWith('.json.gz'))
    .sort()
    .map((f) => analyseRecording(loadFixture(path.join(dir!, f))));

  const byExercise = new Map<string, RecordingResult[]>();
  results.forEach((r) =>
    byExercise.set(r.fixture.exercise, [...(byExercise.get(r.fixture.exercise) ?? []), r])
  );
  const mean = (a: number[]) => a.reduce((s, x) => s + x, 0) / Math.max(1, a.length);
  const median = (a: number[]) => [...a].sort((x, y) => x - y)[Math.floor(a.length / 2)];

  const rows = [...byExercise.entries()].map(([exercise, rs]) => {
    const err = rs.map((r) => r.peak - r.groundTruthPeak).filter(Number.isFinite);
    // Motion-capture outliers (a marker swapped or lost) are excluded from angle error
    const clean = err.filter((e) => Math.abs(e) < 60);
    const views = new Map<string, number>();
    rs.forEach((r) => views.set(r.view, (views.get(r.view) ?? 0) + 1));
    return [
      exercise.replace(/_/g, ' '),
      rs[0].fixture.plane,
      String(rs.length),
      `${rs.filter((r) => Math.abs(r.analysis.reps.length - r.groundTruthReps) <= 1).length}/${rs.length}`,
      clean.length ? `${mean(clean) >= 0 ? '+' : ''}${mean(clean).toFixed(1)}°` : 'n/a',
      clean.length ? `${median(clean.map(Math.abs)).toFixed(1)}°` : 'n/a',
      [...views.entries()].map(([v, n]) => `${v} ${n}`).join(', '),
      `${rs.filter((r) => r.analysis.findings.some((f) => f.severity === 'flag')).length}/${rs.length}`,
      `${rs.filter((r) => r.analysis.findings.length > 0).length}/${rs.length}`,
    ];
  });

  const header = [
    'Exercise',
    'Plane',
    'Recordings',
    'Reps within ±1 of mocap',
    'Peak angle bias',
    'Median abs peak error',
    'Camera view detected',
    'Sessions with a flagged compensation',
    'Sessions with any finding',
  ];
  const table = [header, header.map(() => '---'), ...rows]
    .map((r) => `| ${r.join(' | ')} |`)
    .join('\n');
  const md = `# Real-human benchmark results\n\nGenerated by \`src/testing/recordedPatient/__tests__/benchmark.test.ts\` on ${results.length} recordings (8 healthy adults x 8 exercises, one missing) from Clemente et al., Sensors 2024 (CC BY 4.0). All participants performed the exercises correctly, so every flagged compensation is a false alarm. See REAL_HUMAN_VALIDATION.md for method and interpretation.\n\n${table}\n`;
  const out = process.env.BENCHMARK_OUT;
  if (out) fs.writeFileSync(out, md);
  console.log(md);
  expect(results.length).toBeGreaterThan(0);
});
